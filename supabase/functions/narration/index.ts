// narration: generates missing narration audio with InWorld TTS and caches it in
// Supabase Storage. Replaces the Replit server's /api/places/:id/audio-url and
// /fact-audio routes (server/routes.ts:244-345 in the Expo repo), using the same
// voices, buckets and file names so existing audio keeps working.
//
// POST { curioId: "CURIO-41", language: "fr" }  → overview narration
// POST { curioId: "CURIO-41", factId: "<uuid>" } → English fact narration
//
// Response: { status: "ready" | "generating", bucket, path, loading? }
//   - Facts are short, so they're generated during the request and come back "ready".
//   - Overviews are generated in the background and come back "generating". The app
//     then polls the file's public URL; it doesn't call this function again.
//     For English, `loading` points at the "just getting information" clip to play meanwhile.
//
// Differences from the Replit server:
//   - Missing buckets are created PUBLIC, because the app streams public URLs
//     (supabase/proposed/04_public_audio_buckets.sql).
//   - Only visible places are narrated.
//   - Within one function instance, a file already being generated isn't requested again.
//   - Facts that share a created_at with another fact of the same place get audio keyed
//     by fact id (en_curio_<n>_fact_<uuid>.mp3), because their position is arbitrary.
//
// Secrets: INWORLD_API_KEY (`supabase secrets set INWORLD_API_KEY=...`).
// SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are provided by the platform.
// Deploy: `supabase functions deploy narration`. JWT verification stays on: the app
// sends the user's session or the anon key.

import { createClient, type SupabaseClient } from "jsr:@supabase/supabase-js@2";
import { decodeBase64 } from "jsr:@std/encoding@1/base64";

declare const EdgeRuntime: { waitUntil(promise: Promise<unknown>): void };

/** Overview voices by language (routes.ts:67-78). English is Olivia. */
const OVERVIEW_VOICES: Record<string, string> = {
  en: "Olivia",
  fr: "Hélène",
  de: "Johanna",
  it: "Orietta",
  pt: "Beatriz",
  es: "Sofia",
  ja: "Asuka",
  ar: "Nour",
  zh: "Xiaoyin",
  ko: "Minji",
  hi: "Riya",
};
const FACT_VOICE = "Clive";
const LOADING_CLIP = { bucket: "en_audio", path: "en_loading_overview.mp3" };
const LOADING_TEXT = "I'm just getting information on this place - I'll be ready in a moment.";

/** Files being generated by this instance, so concurrent requests don't call InWorld twice. */
const inFlight = new Map<string, Promise<void>>();

type AudioFile = { bucket: string; path: string };

Deno.serve(async (req) => {
  if (req.method !== "POST") return json({ error: "Method not allowed" }, 405);

  const body = await req.json().catch(() => ({}));
  const curioId = typeof body.curioId === "string" ? body.curioId : "";
  const match = /^CURIO-(\d+)$/.exec(curioId);
  if (!match) return json({ error: "Invalid curio ID" }, 400);
  const number = parseInt(match[1], 10);

  const apiKey = Deno.env.get("INWORLD_API_KEY");
  if (!apiKey) return json({ error: "Narration isn't configured" }, 503);

  const admin = createClient(
    Deno.env.get("SUPABASE_URL")!,
    Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!,
  );

  try {
    if (typeof body.factId === "string") {
      return await factNarration(admin, apiKey, curioId, number, body.factId);
    }
    const language = typeof body.language === "string" ? body.language : "en";
    return await overviewNarration(admin, apiKey, curioId, number, language);
  } catch (error) {
    console.error("[narration]", curioId, error);
    return json({ error: "Internal error" }, 500);
  }
});

async function overviewNarration(
  admin: SupabaseClient,
  apiKey: string,
  curioId: string,
  number: number,
  language: string,
): Promise<Response> {
  const voice = OVERVIEW_VOICES[language];
  if (!voice) return json({ error: "Unsupported language" }, 400);

  const file = { bucket: `${language}_audio`, path: `${language}_curio_${number}_detail_overview.mp3` };
  if (await exists(admin, file)) return json({ status: "ready", ...file });

  const column = language === "en" ? "detail_overview" : `${language}_detail_overview`;
  const { data: place, error } = await admin
    .from("places")
    .select(column)
    .eq("curio_id", curioId)
    .eq("visible_flag", true)
    .maybeSingle();
  if (error) throw error;
  const text = (place as Record<string, string | null> | null)?.[column]?.trim();
  if (!text) return json({ error: "No text to narrate" }, 404);

  EdgeRuntime.waitUntil(
    generateOnce(admin, apiKey, file, text, voice)
      .catch((error) => console.error("[narration]", file.path, error)),
  );

  // As the server did, only English plays the loading clip while it waits.
  let loading: AudioFile | null = null;
  if (language === "en") {
    try {
      await generateOnce(admin, apiKey, LOADING_CLIP, LOADING_TEXT, "Olivia", { skipIfExists: true });
      loading = LOADING_CLIP;
    } catch (error) {
      console.error("[narration] loading clip", error);
    }
  }
  return json({ status: "generating", ...file, loading });
}

async function factNarration(
  admin: SupabaseClient,
  apiKey: string,
  curioId: string,
  number: number,
  factId: string,
): Promise<Response> {
  // Position among all the place's facts by created_at, as the server numbered them.
  const { data: facts, error } = await admin
    .from("facts")
    .select("id, fact_info, language_code, created_at")
    .eq("curio_id", curioId)
    .order("created_at", { ascending: true });
  if (error) throw error;

  const index = (facts ?? []).findIndex((fact) => fact.id === factId);
  if (index === -1) return json({ error: "Fact not found" }, 404);
  const fact = facts![index];
  if ((fact.language_code ?? "en").toLowerCase() !== "en") {
    return json({ error: "Fact audio is English only" }, 400);
  }

  const text = String(fact.fact_info ?? "")
    .replace(/https?:\/\/\S+/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!text) return json({ error: "No text to narrate" }, 404);

  // Bulk-imported facts share a created_at, so their order (and position) is arbitrary.
  // Those are keyed by fact id instead, matching NarrationLocator.factPath in the app.
  const positionIsReliable = facts!.filter((other) => other.created_at === fact.created_at).length === 1;
  const path = positionIsReliable
    ? `en_curio_${number}_fact_${String(index + 1).padStart(2, "0")}_v2.mp3`
    : `en_curio_${number}_fact_${factId}.mp3`;
  const file = { bucket: "en_audio", path };
  await generateOnce(admin, apiKey, file, text, FACT_VOICE, { skipIfExists: true });
  return json({ status: "ready", ...file });
}

/** Generates and uploads `file` unless this instance is already doing so. */
function generateOnce(
  admin: SupabaseClient,
  apiKey: string,
  file: AudioFile,
  text: string,
  voice: string,
  options: { skipIfExists?: boolean } = {},
): Promise<void> {
  const key = `${file.bucket}/${file.path}`;
  const running = inFlight.get(key);
  if (running) return running;

  const job = (async () => {
    if (options.skipIfExists && (await exists(admin, file))) return;
    console.log(`[narration] generating ${key} (${text.length} chars, ${voice})`);
    const audio = await synthesize(text, voice, apiKey);
    await ensurePublicBucket(admin, file.bucket);
    const { error } = await admin.storage
      .from(file.bucket)
      .upload(file.path, audio, { contentType: "audio/mpeg", upsert: false });
    // Another instance may have uploaded it first; that's fine.
    if (error && !/already exists|duplicate/i.test(error.message)) throw error;
    console.log(`[narration] done ${key}`);
  })().finally(() => inFlight.delete(key));

  inFlight.set(key, job);
  return job;
}

/** InWorld TTS, with the server's settings (routes.ts:17-37). */
async function synthesize(text: string, voice: string, apiKey: string): Promise<Uint8Array> {
  const response = await fetch("https://api.inworld.ai/tts/v1/voice", {
    method: "POST",
    headers: { Authorization: `Basic ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      text,
      voice_id: voice,
      audio_config: { audio_encoding: "MP3", speaking_rate: 1 },
      temperature: 1.1,
      model_id: "inworld-tts-1.5-max",
    }),
  });
  if (!response.ok) {
    throw new Error(`InWorld ${response.status}: ${await response.text().catch(() => "")}`);
  }
  const { audioContent } = await response.json() as { audioContent?: string };
  if (!audioContent) throw new Error("InWorld returned no audio");
  return decodeBase64(audioContent);
}

async function exists(admin: SupabaseClient, file: AudioFile): Promise<boolean> {
  const { data, error } = await admin.storage.from(file.bucket).list("", { search: file.path });
  return !error && !!data?.some((entry) => entry.name === file.path);
}

async function ensurePublicBucket(admin: SupabaseClient, bucket: string): Promise<void> {
  const { data } = await admin.storage.getBucket(bucket);
  if (data) return;
  const { error } = await admin.storage.createBucket(bucket, { public: true });
  if (error && !/already exists|duplicate/i.test(error.message)) throw error;
}

function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "Content-Type": "application/json" },
  });
}
